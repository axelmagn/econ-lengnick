// TYPES
//
// ============================================================================

typedef struct {
  float position[3];
  float color[4];
} vertex_t;

static struct {
  sg_pipeline pip;
  sg_bindings bind;
  sg_pass_action pass_action;
  float bg_color[3];

  // main framebuffer
  sfb_framebuffer framebuffer;
  uint8_t pixels[WORLD_SIZE_X][WORLD_SIZE_Y];
  uint32_t palette[256];
} state;

